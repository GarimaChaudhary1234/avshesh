// Checks that the lived-in demo city (DemoDataExtras) really gives every role something to look at.
// Run it against a stack started with the default settings (DEMO_RICH on, fresh database):
//   docker compose down -v && docker compose up -d && node tests/api/rich-demo.mjs
// It only reads. It is not part of run-all.sh, which starts from the small demo data on purpose.
import { call, check, group, login, summary } from './harness.mjs'

const as = async (phone) => (await login(phone)).token

group('Commissioner: a city with several wards in different states')
const commissioner = await as('9000000200')
let r = await call('GET', '/municipal/wards', { token: commissioner })
const rows = Object.fromEntries(r.json.wards.map((w) => [w.ward.id, w]))
check('four wards have an officer', r.json.summary.wardsWithOfficer === 4, JSON.stringify(r.json.summary))
check('27 households are registered across the wards', r.json.summary.registeredHouseholds >= 27, JSON.stringify(r.json.summary))
check('ward 12, 30 and 2 hold their households', rows[12].registeredHouseholds >= 5 && rows[30].registeredHouseholds >= 6 && rows[2].registeredHouseholds >= 2, JSON.stringify([12, 30, 2].map((i) => rows[i].registeredHouseholds)))
check('ward 30 has an open payment dispute', rows[30].openDisputes === 1, JSON.stringify(rows[30]))
check('ward 2 needs attention: requests waiting, a dealer to approve', rows[2].openRequests >= 2 && rows[2].pendingDealers === 1, JSON.stringify(rows[2]))
check('wards 12 and 30 have finished pickups (trips) and the homes they collected from, and a share kept out of the dump', rows[12].pickups === 1 && rows[12].collections === 5 && rows[30].pickups === 2 && rows[30].collections === 7 && rows[12].keptFromDumpPercent > 0, JSON.stringify([[12, 30].map((i) => [rows[i].pickups, rows[i].collections])]))
check('every ward with households has a ward (no household landed in the wrong ward)', r.json.summary.registeredHouseholds === Object.values(rows).reduce((a, w) => a + w.registeredHouseholds, 0), '')
r = await call('GET', '/municipal/activity', { token: commissioner })
check('the city activity feed has entries from several wards', r.json.length >= 15 && new Set(r.json.map((a) => a.wardId)).size >= 4, `${r.json.length} entries`)
r = await call('GET', '/municipal/wards/30', { token: commissioner })
check('ward 30 page: officer, two workers with logins, a dealer and a compost center', r.json.officers.length === 1 && r.json.staff.length === 2 && r.json.staff.every((s) => s.hasLogin) && r.json.dealers.length >= 2, JSON.stringify([r.json.officers.length, r.json.staff.length, r.json.dealers.length]))

group('Ward officers see their own ward')
const officer12 = await as('9000000211')
r = await call('GET', '/municipal/overview', { token: officer12 })
check('the officer of ward 12 sees a ward with one finished pickup of 5 homes and a waiting request', r.json.ward.id === 12 && r.json.impact.pickups === 1 && r.json.impact.collections === 5 && r.json.openRequests >= 1, JSON.stringify(r.json.ward) + JSON.stringify(r.json.impact))
r = await call('GET', '/municipal/collectors', { token: officer12 })
check('and a dealer waiting for approval (the compost works)', r.json.some((c) => c.verification === 'PENDING') && r.json.some((c) => c.verification === 'VERIFIED' && c.rating !== null), JSON.stringify(r.json.map((c) => [c.businessName, c.verification, c.rating])))
const officer30 = await as('9000000212')
r = await call('GET', '/municipal/disputes', { token: officer30 })
check('the officer of ward 30 has a payment dispute to resolve', r.json.some((d) => d.status === 'DISPUTED' && d.householdName === 'Shweta Dash'), JSON.stringify(r.json.map((d) => [d.householdName, d.status])))
const officer15 = await as('9000000201')
r = await call('GET', '/municipal/requests', { token: officer15 })
const statuses = new Set(r.json.map((x) => x.status))
check('ward 15 requests are in every status: open, scheduled, collected, rejected', ['OPEN', 'SCHEDULED', 'COLLECTED', 'REJECTED'].every((s) => statuses.has(s)), [...statuses].join(','))

group('Collection workers have pickups')
r = await call('GET', '/staff/tasks', { token: await as('9000000301') })
check('Mahesh (ward 15) has a pickup to do and one he finished', r.json.open.length === 1 && r.json.done.length === 1, JSON.stringify([r.json.open.length, r.json.done.length]))
r = await call('GET', '/staff/tasks', { token: await as('9000000311') })
check('Tapan (ward 12) has a scheduled pickup', r.json.open.length === 1, JSON.stringify(r.json))
r = await call('GET', '/staff/tasks', { token: await as('9000000313') })
check('Dillip (ward 30) has finished one', r.json.done.length === 1, JSON.stringify(r.json))

group('Dealers and compost centers')
const ramesh = await as('9000000101')
r = await call('GET', '/collector/pools', { token: ramesh })
check('Ramesh sees a READY pool in the second mohalla to accept, with a mix of items', r.json.some((p) => p.ready && p.items.length >= 3), JSON.stringify(r.json.map((p) => [p.name, p.ready, p.items.length])))
const biswajit = await as('9000000111')
r = await call('GET', '/collector/pickups', { token: biswajit })
check('Biswajit has one finished and one scheduled pickup', r.json.some((p) => p.status === 'DONE') && r.json.some((p) => p.status === 'SCHEDULED'), JSON.stringify(r.json.map((p) => p.status)))
r = await call('GET', '/collector/earnings?days=30', { token: biswajit })
check('with earnings', r.json.profit > 0 && r.json.kg > 40, JSON.stringify(r.json))
r = await call('GET', '/collector/rating', { token: biswajit })
check('and ratings from households', r.json.summary.count >= 3 && r.json.summary.average >= 4, JSON.stringify(r.json.summary))
r = await call('GET', '/collector/earnings?days=30', { token: await as('9000000115') })
check('the compost center collected food waste', r.json.compostKg > 0 || r.json.kg > 50, JSON.stringify(r.json))
r = await call('GET', '/collector/profile', { token: await as('9000000113') })
check('a dealer in ward 2 is still waiting for approval', r.json.verification === 'PENDING', JSON.stringify(r.json))

group('Households see their world')
const sneha = await as('9000000015')
r = await call('GET', '/listings/mine', { token: sneha })
check('Sneha (ward 12) has a finished, paid listing and a scheduled pickup', r.json.some((l) => l.status === 'DONE' && l.paymentStatus === 'CONFIRMED') && r.json.some((l) => l.status === 'SCHEDULED' && l.pickupStart), JSON.stringify(r.json.map((l) => [l.status, l.paymentStatus])))
r = await call('GET', '/home', { token: sneha })
check('her home shows earnings and a share kept out of the dump', r.json.earnedThisMonth > 0 && r.json.keptFromDumpPercent > 0, JSON.stringify([r.json.earnedThisMonth, r.json.keptFromDumpPercent]))
r = await call('GET', '/listings/mine', { token: await as('9000000023') })
check('Shweta (ward 30) disputed her payment', r.json.some((l) => l.paymentStatus === 'DISPUTED'), JSON.stringify(r.json.map((l) => l.paymentStatus)))
r = await call('GET', '/me/notifications', { token: sneha })
check('households have notifications', r.json.items.length >= 2, JSON.stringify(r.json.items.map((n) => n.code)))
r = await call('GET', '/municipal-requests/mine', { token: await as('9000000017') })
check('a household has a municipal request scheduled with a worker\'s name', r.json.some((x) => x.status === 'SCHEDULED' && x.staffName === 'Tapan Barik'), JSON.stringify(r.json))
r = await call('GET', '/pools/mine', { token: await as('9000000027') })
check('households of ward 2 wait in a pool no dealer serves yet', r.json.length === 1 && r.json[0].status === 'FILLING', JSON.stringify(r.json))

group('The public numbers')
r = await call('GET', '/impact')
check('public impact has real figures from several wards', r.json.kgDiverted > 250 && r.json.collections >= 15 && r.json.pickups === 4 && r.json.pickups < r.json.collections && r.json.keptFromDumpPercent > 0, JSON.stringify(r.json))

process.exit(summary() ? 1 : 0)
